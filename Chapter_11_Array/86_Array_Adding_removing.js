let arr = [10, 20, 30];
console.log(arr);

// Add to END
arr.push(40);
console.log(arr);

// Remove from END
arr.pop();
console.log(arr);

arr.push(50, 60);  //multiple add at the end
console.log(arr);

// Add to BEGINNING
arr.unshift(7);
console.log(arr);


// Remove from BEGINNING
arr.shift();
console.log(arr);

arr.unshift(100);
console.log(arr);
arr.shift();
console.log(arr);